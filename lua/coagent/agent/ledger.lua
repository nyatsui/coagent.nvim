  ['makefile'] = 92, ['dockerfile'] = 85, ['agents.md'] = 90, ['claude.md'] = 88, ['justfile'] = 85,
  ['package.json'] = 90, ['cargo.toml'] = 90, ['go.mod'] = 90,
