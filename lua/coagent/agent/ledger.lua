function Ledger:view(name, n)
  local text = M.bounded(self:read(name), name == 'decisions' and 'D' or 'S', n or self.config.recent or 10, { label = name })
  return '# ' .. M.TITLES[name] .. '\n\n' .. text .. '\n'
end

