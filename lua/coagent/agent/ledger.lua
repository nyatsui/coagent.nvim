function Ledger:_history_dir()
  return self:dir() .. '/.history'
end

--- Snapshots, oldest first: { name, path, index, label, time }.
---@return table[]
function Ledger:snapshots()
  local out = {}
  local dir = self:_history_dir()
  if vim.fn.isdirectory(dir) == 0 then
    return out
  end
  for name, typ in vim.fs.dir(dir) do
    local idx, label = name:match('^(%d+)%-(.*)$')
    if typ == 'directory' and idx then
      local info = util.json_decode(util.read_file(dir .. '/' .. name .. '/.snapshot.json') or '') or {}
      table.insert(out, { name = name, path = dir .. '/' .. name, index = tonumber(idx), label = info.label or label, time = info.time })
    end
  end
  table.sort(out, function(a, b)
    return a.index < b.index
  end)
  return out
end

--- Copy the ledger files as they are now, before coagent writes (kept:
--- ledger.history_max). /ledger undo restores the newest one.
---@param label string what is about to change
---@return string? path
function Ledger:snapshot(label)
  if not self:exists() then
    return nil
  end
  local list = self:snapshots()
  local idx = (#list > 0 and list[#list].index or 0) + 1
  local path = string.format('%s/%06d-%s', self:_history_dir(), idx, (label or 'change'):gsub('[^%w%-_]', '_'):sub(1, 40))
  ensure_dir(self:_history_dir())
  ensure_dir(path)
  for _, name in ipairs(M.FILES) do
    local text = util.read_file(self:path(name))
    if text then
      write(path .. '/' .. name .. '.md', text)
    end
  end
  local meta = util.read_file(self:dir() .. '/.meta.json')
  if meta then
    write(path .. '/.meta.json', meta)
  end
  write(path .. '/.snapshot.json', vim.json.encode({ label = label, time = os.time() }))
  table.insert(list, { path = path })
  local keep = self.config.history_max or 20
  for i = 1, #list - keep do
    vim.fn.delete(list[i].path, 'rf')
  end
  return path
end

--- Restore the newest snapshot (what the ledger was before coagent's last
--- write) and drop it.
---@return table? snapshot, string? err
function Ledger:undo()
  local list = self:snapshots()
  local snap = list[#list]
  if not snap then
    return nil, 'nothing to undo (no snapshot of the ledger)'
  end
  if self:busy() then
    return nil, 'a ledger request is running; wait for it to finish'
  end
  for _, name in ipairs(M.FILES) do
    if self:_dirty(name) then
      return nil, name .. '.md has unsaved changes in a buffer; save or discard them first'
    end
  end
  for _, name in ipairs(M.FILES) do
    local text = util.read_file(snap.path .. '/' .. name .. '.md')
    if text then
      self:_write(name, text)
    end
  end
  local meta = util.read_file(snap.path .. '/.meta.json')
  if meta then
    write(self:dir() .. '/.meta.json', meta)
  end
  vim.fn.delete(snap.path, 'rf')
  return snap
end

---@param name string
---@return string
function Ledger:read(name)
  return util.read_file(self:path(name)) or ''
end

--- Loaded buffer of a ledger file with unsaved changes?
function Ledger:_dirty(name)
  local buf = util.find_buf(self:path(name))
  return buf ~= nil and vim.bo[buf].modified
end

--- Write a ledger file; reload an open (unmodified) buffer of it.
function Ledger:_write(name, text)
  ensure_dir(self:dir())
  local path = self:path(name)
  local ok, err = write(path, text)
  local buf = util.find_buf(path)
  if ok and buf and not vim.bo[buf].modified then
    pcall(vim.api.nvim_buf_call, buf, function()
      vim.cmd('silent! edit')
    end)
  end
  return ok, err
end

---@class Coagent.LedgerPending
---@field file string
---@field section string
---@field proposed string
---@field time integer
---@field reason string

--- Replace sections of `name` with `proposed` (section name -> body), never
--- overwriting a section you edited (its text differs from what coagent last
--- wrote) or a file with unsaved changes in a buffer: those updates are kept
--- in meta.pending for /ledger review.
---@param name string
---@param proposed table<string,string>
---@param order string[]? section order for new sections (default M.SECTIONS[name])
---@return {applied:string[], pending:string[]}
function Ledger:update_sections(name, proposed, order)
  self:ensure()
  local m = self:_meta()
  local result = { applied = {}, pending = {} }
  local dirty = self:_dirty(name)
  local doc = M.parse(self:read(name))
  if doc.preamble == '' then
    doc.preamble = M.parse(template(name)).preamble
  end
  local written = m.written[name] or {}
  m.written[name] = written
  local function add_pending(sec, body, reason)
    for i = #m.pending, 1, -1 do
      local p = m.pending[i]
      if p.file == name and p.section:lower() == sec:lower() then
        table.remove(m.pending, i)
      end
    end
    table.insert(m.pending, { file = name, section = sec, proposed = body, time = os.time(), reason = reason })
    table.insert(result.pending, sec)
  end
  local names = {}
  for _, s in ipairs(order or M.SECTIONS[name] or {}) do
    if proposed[s] ~= nil then
      table.insert(names, s)
    end
  end
  for s in pairs(proposed) do
    if not vim.tbl_contains(names, s) then
      table.insert(names, s)
    end
  end
  local changed = false
  for _, sec in ipairs(names) do
    local new = body_of(proposed[sec])
    local cur = M.section(doc, sec)
    if dirty then
      add_pending(sec, new, 'unsaved buffer')
    elseif not cur then
      table.insert(doc.sections, { name = sec, body = new })
      written[sec] = M.section_hash(new)
      table.insert(result.applied, sec)
      changed = true
    else
      local cur_hash = M.section_hash(cur.body)
      local base = written[cur.name]
      if cur_hash == M.section_hash(new) then
        written[cur.name] = cur_hash -- same text: nothing to protect
      elseif base == cur_hash or (base == nil and M.is_placeholder(cur.body)) then
        cur.body = new
        written[cur.name] = M.section_hash(new)
        table.insert(result.applied, cur.name)
        changed = true
      else
        add_pending(cur.name, new, 'edited by you')
      end
    end
  end
  if changed then
    self:_write(name, M.render(doc))
  end
  self:_save_meta(m)
  return result
end

--- Pending updates of sections you edited.
---@return Coagent.LedgerPending[]
function Ledger:pending()
  return self:_meta().pending
end

--- Unified diff of a pending update (your current text -> the proposal).
---@param p Coagent.LedgerPending
---@return string
function Ledger:pending_diff(p)
  local cur = M.section(M.parse(self:read(p.file)), p.section)
  local old = (cur and body_of(cur.body) or '') .. '\n'
  local new = body_of(p.proposed) .. '\n'
  return require('coagent.core.diff').unified(old, new, p.file .. '.md#' .. p.section)
end

--- Apply (`'apply'`) or drop (`'keep'`: your text stays and becomes the new
--- baseline) a pending update.
---@param index integer
---@param action 'apply'|'keep'
---@return boolean ok, string? err
function Ledger:resolve(index, action)
  local m = self:_meta()
  local p = m.pending[index]
  if not p then
    return false, 'no pending update ' .. tostring(index)
  end
  if self:_dirty(p.file) then
    return false, p.file .. '.md has unsaved changes in a buffer; save it first'
  end
  table.remove(m.pending, index)
  local doc = M.parse(self:read(p.file))
  local cur = M.section(doc, p.section)
  m.written[p.file] = m.written[p.file] or {}
  if action == 'apply' then
    if cur then
      cur.body = p.proposed
    else
      table.insert(doc.sections, { name = p.section, body = p.proposed })
    end
    m.written[p.file][p.section] = M.section_hash(p.proposed)
    self:_write(p.file, M.render(doc))
  else
    m.written[p.file][cur and cur.name or p.section] = cur and M.section_hash(cur.body) or nil
  end
  self:_save_meta(m)
  return true
end

