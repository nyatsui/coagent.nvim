---@class Coagent.LedgerEntry
---@field id integer
---@field prefix string 'S' | 'D' | 'F'
---@field header string
---@field date string?
---@field kind string? subtasks only
---@field title string
---@field body string
---@field fields table<string,string> "- Key: value" bullets (lowercase keys, first line)

--- Entries "### <prefix>-<n> · ..." anywhere in the file (newest last).
---@param text string?
---@param prefix 'S'|'D'|'F'
---@return Coagent.LedgerEntry[]
function M.entries(text, prefix)
  local out, cur, fence = {}, nil, false
  for _, line in ipairs(vim.split(text or '', '\n', { plain = true })) do
    local id, rest
    if not fence then
      id, rest = line:match('^###%s+' .. prefix .. '%-(%d+)%s*(.-)%s*$')
    end
    if is_fence(line) then
      fence = not fence
    end
    if id then
      cur = { id = tonumber(id), prefix = prefix, header = line, rest = rest, lines = {} }
      table.insert(out, cur)
    elseif cur then
      if not fence and line:match('^##?%s') then
        cur = nil -- a new section ends the entry
      else
        table.insert(cur.lines, line)
      end
    end
  end
  for _, e in ipairs(out) do
    e.body = vim.trim(table.concat(e.lines, '\n'))
    e.lines = nil
    local rest = e.rest:gsub('^' .. vim.pesc(vim.trim(SEP)) .. '%s*', ''):gsub('^[:%-]%s*', '')
    e.rest = nil
    local parts = vim.split(rest, SEP, { plain = true, trimempty = true })
    if #parts >= 2 and parts[1]:match('^%d%d%d%d%-%d%d%-%d%d$') then
      e.date = table.remove(parts, 1)
      if prefix == 'S' and #parts >= 2 then
        e.kind = table.remove(parts, 1)
      end
    end
    e.title = vim.trim(table.concat(parts, SEP))
    e.fields = {}
    for _, line in ipairs(vim.split(e.body, '\n', { plain = true })) do
      local key, value = line:match('^%- ([%w][%w ]-):%s*(.*)$')
      if key and not e.fields[key:lower()] then
        e.fields[key:lower()] = vim.trim(value)
      end
    end
  end
  return out
end

--- "S-4 · 2026-10-12 · local · title — outcome"
---@param e Coagent.LedgerEntry
---@param max integer?
function M.one_line(e, max)
  local parts = { e.prefix .. '-' .. e.id }
  if e.date then
    table.insert(parts, e.date)
  end
  if e.kind then
    table.insert(parts, e.kind)
  end
  table.insert(parts, e.title ~= '' and e.title or '(untitled)')
  local line = table.concat(parts, SEP)
  local extra = e.fields.outcome or e.fields.reason or e.fields.finding or e.fields.note
  if extra and extra ~= '' then
    line = line .. ' — ' .. extra
  end
  return util.ellipsize(line, max or 200)
end

--- The recent `n` entries in full plus a one-line summary of the older ones
--- (the newest `older_lines` of them; the rest only counted).
---@param text string? file content
---@param prefix 'S'|'D'
---@param n integer
---@param opts {older_lines:integer?, label:string?}?
---@return string markdown, integer total
function M.bounded(text, prefix, n, opts)
  opts = opts or {}
  local es = M.entries(text, prefix)
  if #es == 0 then
    return '_(no entries yet)_', 0
  end
  local out = {}
  local first = math.max(1, #es - n + 1)
  if first > 1 then
    local older_lines = opts.older_lines or 30
    table.insert(out, string.format('Summary of %d older %s (one line each; full history in the file):', first - 1, opts.label or 'entries'))
    local from = 1
    if first - 1 > older_lines then
      from = first - older_lines
      table.insert(out, string.format('- %s-%d … %s-%d: %d earlier entries not shown', prefix, es[1].id, prefix, es[from - 1].id, from - 1))
    end
    for i = from, first - 1 do
      table.insert(out, '- ' .. M.one_line(es[i], 160))
    end
    table.insert(out, '')
  end
  for i = first, #es do
    local e = es[i]
    table.insert(out, e.header .. (e.body ~= '' and ('\n' .. e.body) or ''))
    table.insert(out, '')
  end
  return vim.trim(table.concat(out, '\n')), #es
end

