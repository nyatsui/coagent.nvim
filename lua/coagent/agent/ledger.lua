local function is_fence(line)
  return line:match('^%s*```') ~= nil or line:match('^%s*~~~') ~= nil
end

---@class Coagent.LedgerDoc
---@field preamble string text before the first "## " header ("# Title", notes)
---@field sections {name:string, body:string}[]

--- Split a file into its "## " sections (headers inside code fences ignored).
---@param text string?
---@return Coagent.LedgerDoc
function M.parse(text)
  local pre, sections, cur, fence = {}, {}, nil, false
  for _, line in ipairs(vim.split(text or '', '\n', { plain = true })) do
    local name = not fence and line:match('^##%s+(.-)%s*$') or nil
    if is_fence(line) then
      fence = not fence
    end
    if name and name ~= '' then
      cur = { name = name, lines = {} }
      table.insert(sections, cur)
    elseif cur then
      table.insert(cur.lines, line)
    else
      table.insert(pre, line)
    end
  end
  for _, s in ipairs(sections) do
    s.body = vim.trim(table.concat(s.lines, '\n'))
    s.lines = nil
  end
  return { preamble = vim.trim(table.concat(pre, '\n')), sections = sections }
end

---@param doc Coagent.LedgerDoc
---@param name string
---@return {name:string, body:string}?, integer?
function M.section(doc, name)
  local want = name:lower()
  for i, s in ipairs(doc.sections) do
    if s.name:lower() == want then
      return s, i
    end
  end
end

local function body_of(text)
  text = vim.trim(text or '')
  return text ~= '' and text or M.PLACEHOLDER
end

---@param doc Coagent.LedgerDoc
---@return string
function M.render(doc)
  local out = { doc.preamble }
  for _, s in ipairs(doc.sections) do
    table.insert(out, '## ' .. s.name .. '\n\n' .. body_of(s.body))
  end
  return table.concat(out, '\n\n') .. '\n'
end

--- Hash of a section body as compared for user edits.
function M.section_hash(body)
  return sha(body_of(body))
end

local function strip_comments(text)
  return (text:gsub('<!%-%-.-%-%->%s*', ''))
end
M.strip_comments = strip_comments

local function template(name)
  local doc = { preamble = '# ' .. M.TITLES[name] .. '\n\n<!-- coagent ledger: ' .. NOTES[name] .. ' -->', sections = {} }
  for _, s in ipairs(M.SECTIONS[name]) do
    table.insert(doc.sections, { name = s, body = (name == 'decisions' or name == 'subtasks') and '' or M.PLACEHOLDER })
  end
  local text = M.render(doc)
  if name == 'decisions' or name == 'subtasks' then
    -- the log section starts empty (no placeholder between its entries)
    text = text:gsub('\n\n' .. vim.pesc(M.PLACEHOLDER) .. '\n$', '\n')
  end
  return text
end
M.template = template

--- Is a section body still only the placeholder (nothing written yet)?
function M.is_placeholder(body)
  local b = vim.trim(body or '')
  return b == '' or b == M.PLACEHOLDER
end

--- Model-written text must not create headers (that would change the file
--- structure or fake entries): a leading "#" becomes bold text.
---@param text string?
---@param max integer
---@return string
local function clean_block(text, max)
  text = util.redact(vim.trim(tostring(text or '')))
  local out = {}
  for _, line in ipairs(vim.split(text, '\n', { plain = true })) do
    local h = line:match('^%s*#+%s*(.-)%s*$')
    table.insert(out, h and (h ~= '' and ('**' .. h .. '**') or '') or line)
  end
  return util.clip(vim.trim(table.concat(out, '\n')), max)
end
M.clean_block = clean_block

---@param text string?
---@param max integer
---@return string
local function clean_line(text, max)
  local s = util.redact(vim.trim(tostring(text or ''))):gsub('%s*\n%s*', ' '):gsub('^#+%s*', '')
  return util.ellipsize(s, max)
end
M.clean_line = clean_line

--- A multi-line field value inside a "- Key: value" bullet: continuation
--- lines are indented so they stay part of the bullet.
local function field(key, value)
  local lines = vim.split(value, '\n', { plain = true })
  for i = 2, #lines do
    lines[i] = lines[i] ~= '' and ('  ' .. lines[i]) or ''
  end
  return '- ' .. key .. ': ' .. table.concat(lines, '\n')
end

