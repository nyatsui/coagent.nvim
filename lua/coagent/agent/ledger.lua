--- How central a file is for understanding the project (higher first; 0 = skip).
---@param p string
---@return integer
function M.score(p)
  local base = vim.fs.basename(p):lower()
  local ext = base:match('%.([%w]+)$') or ''
  if BINARY[ext] then
    return 0
  end
  local depth = select(2, p:gsub('/', ''))
  local in_tests = p:match('^tests?/') or p:match('/tests?/') or base:match('^test_') or base:match('_test%.py$')
  local s
  if CORE_NAMES[base] then
    s = CORE_NAMES[base]
  elseif base:match('^requirements.*%.txt$') then
    s = 96
  elseif ext == 'py' and not in_tests and (base:match('train') or base:match('^main') or base:match('^run') or base:match('eval') or base:match('infer') or base:match('predict') or base:match('finetune')) then
    s = 90
  elseif ext == 'py' and not in_tests and (base:match('model') or base:match('net') or base:match('arch') or base:match('dataset') or base:match('data') or base:match('loader') or base:match('transform') or base:match('loss') or base:match('optim') or base:match('schedul') or base:match('metric') or base:match('config') or base:match('trainer') or base:match('engine') or base:match('module')) then
    s = 80
  elseif (ext == 'yaml' or ext == 'yml' or ext == 'toml' or ext == 'json' or ext == 'cfg' or ext == 'ini') and (p:match('conf') or base:match('config') or base:match('hparam') or base:match('param')) then
    s = 75
  elseif ext == 'py' and not in_tests then
    s = 55
  elseif ext == 'sh' or ext == 'lua' or ext == 'ts' or ext == 'js' or ext == 'go' or ext == 'rs' or ext == 'c' or ext == 'cpp' or ext == 'h' then
    s = in_tests and 15 or 45
  elseif ext == 'yaml' or ext == 'yml' or ext == 'toml' then
    s = 35
  elseif ext == 'md' then
    s = 30
  elseif ext == 'py' then
    s = 20 -- tests
  elseif ext == 'ipynb' then
    s = 10
  else
    return 0
  end
  for part in p:gmatch('([^/]+)/') do
    if DATA_DIRS[part:lower()] then
      s = math.min(s, 5)
    end
  end
  return math.max(1, s - depth * 2)
end

--- Pick and read the core files within the byte budget (highest score first).
---@param paths string[]
---@param opts {max_bytes:integer, max_file_bytes:integer, only:string[]?}
---@return {path:string, content:string, truncated:boolean}[], integer considered
function Ledger:_read_files(paths, opts)
  local ranked = {}
  for _, p in ipairs(opts.only or paths) do
    local s = opts.only and 100 or M.score(p)
    if s > 0 then
      table.insert(ranked, { path = p, score = s })
    end
  end
  table.sort(ranked, function(a, b)
    if a.score ~= b.score then
      return a.score > b.score
    end
    return a.path < b.path
  end)
  local out, total = {}, 0
  for _, r in ipairs(ranked) do
    if total >= opts.max_bytes then
      break
    end
    local info = self.ws:check(r.path)
    local st = info.inside and not info.protected and vim.uv.fs_stat(info.real)
    if st and st.type == 'file' and st.size <= 2 * 1024 * 1024 then
      local abs = info.real
      local data = util.read_file(abs)
      if data and not data:find('\0', 1, true) then
        data = util.redact(data)
        local cap = math.min(opts.max_file_bytes, opts.max_bytes - total)
        local truncated = #data > cap
        if truncated then
          data = util.truncate_middle(data, cap)
        end
        total = total + #data
        table.insert(out, { path = r.path, content = data, truncated = truncated })
      end
    end
  end
  return out, #ranked
end

local function files_block(files)
  local out = {}
  for _, f in ipairs(files) do
    table.insert(out, string.format('<file path="%s"%s>\n%s\n</file>', f.path, f.truncated and ' truncated="true"' or '', f.content))
  end
  return table.concat(out, '\n')
end

