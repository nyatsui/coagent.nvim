-- Appending entries
------------------------------------------------------------------------------

local function next_id(self, m, name, prefix)
  local max = tonumber(m.last_id[name]) or 0
  for _, e in ipairs(M.entries(self:read(name), prefix)) do
    max = math.max(max, e.id)
  end
  for _, q in ipairs(m.queued) do
    if q.file == name then
      max = math.max(max, q.id)
    end
  end
  return max + 1
end

--- Append queued entries once their file has no unsaved buffer.
function Ledger:_flush(m)
  local keep, by_file = {}, {}
  for _, q in ipairs(m.queued) do
    if self:_dirty(q.file) then
      table.insert(keep, q)
    else
      by_file[q.file] = by_file[q.file] or {}
      table.insert(by_file[q.file], q.text)
    end
  end
  for name, blocks in pairs(by_file) do
    local text = self:read(name)
    text = vim.trim(text ~= '' and text or template(name)) .. '\n\n' .. table.concat(blocks, '\n\n') .. '\n'
    self:_write(name, text)
  end
  m.queued = keep
end

--- Append a block to decisions.md / subtasks.md (append-only: your edits
--- elsewhere in the file are untouched). With unsaved changes in a buffer of
--- the file it is queued and appended later.
---@param name 'decisions'|'subtasks'
---@param build fun(id:integer):string block for the entry with that id
---@return integer id
function Ledger:_append(name, build)
  self:ensure()
  local m = self:_meta()
  local prefix = name == 'decisions' and 'D' or 'S'
  local id = next_id(self, m, name, prefix)
  m.last_id[name] = id
  table.insert(m.queued, { file = name, id = id, text = build(id) })
  self:_flush(m)
  self:_save_meta(m)
  if #m.queued > 0 then
    self:_notice('warn', string.format('Ledger: %s.md has unsaved changes; %d entr%s will be appended after you save it.', name, #m.queued, #m.queued == 1 and 'y' or 'ies'))
  end
  return id
end

---@class Coagent.LedgerSubtask
---@field kind string 'local'|'delegated'|'experiment'|'note'
---@field title string?
---@field request string?
---@field result string?
---@field files string[]?
---@field outcome string?
---@field note string?

--- Append a subtask entry (text is cleaned: no headers, secrets redacted).
---@param s Coagent.LedgerSubtask
---@return integer id
function Ledger:add_subtask(s)
  return self:_append('subtasks', function(id)
    local kind = vim.tbl_contains(M.KINDS, s.kind) and s.kind or 'local'
    local title = clean_line(s.title or s.request or s.note or '', 80)
    local lines = { string.format('### S-%d%s%s%s%s%s%s', id, SEP, today(), SEP, kind, SEP, title ~= '' and title or '(untitled)') }
    if s.note then
      table.insert(lines, field('Note', clean_block(s.note, 2000)))
    end
    if s.request then
      table.insert(lines, field('Request', clean_block(s.request, 600)))
    end
    if s.result then
      table.insert(lines, field('Result', clean_block(s.result, 1200)))
    end
    if s.files then
      local f = {}
      for i, p in ipairs(s.files) do
        if i > 30 then
          table.insert(f, '… ' .. (#s.files - 30) .. ' more')
          break
        end
        table.insert(f, '`' .. clean_line(p, 200):gsub('`', '') .. '`')
      end
      table.insert(lines, '- Files changed: ' .. (#f > 0 and table.concat(f, ', ') or 'none'))
    end
    if s.outcome then
      table.insert(lines, field('Outcome', clean_line(s.outcome, 300)))
    end
    return table.concat(lines, '\n')
  end)
end

---@param d {title:string, decision:string?, reason:string?, alternatives:string?, source:string?}
---@return integer id
function Ledger:add_decision(d)
  return self:_append('decisions', function(id)
    local lines = { string.format('### D-%d%s%s%s%s', id, SEP, today(), SEP, clean_line(d.title, 100)) }
    if d.decision and vim.trim(d.decision) ~= '' then
      table.insert(lines, field('Decision', clean_block(d.decision, 600)))
    end
    table.insert(lines, field('Reason', clean_block(d.reason ~= nil and d.reason ~= '' and d.reason or 'not recorded', 600)))
    table.insert(lines, field('Alternatives rejected', clean_block(d.alternatives ~= nil and d.alternatives ~= '' and d.alternatives or 'none recorded', 500)))
    if d.source then
      table.insert(lines, '- Source: ' .. clean_line(d.source, 80))
    end
    return table.concat(lines, '\n')
  end)
end

--- `/ledger note <text>`: a note entry in subtasks.md (no request).
---@param text string
---@return integer? id, string? err
function Ledger:note(text)
  text = vim.trim(text or '')
  if text == '' then
    return nil, 'empty note'
  end
  return self:add_subtask({ kind = 'note', title = text, note = text })
end

--- `/ledger decision <title> [-- reason [-- rejected alternatives]]` (no request).
---@param text string
---@return integer? id, string? err
function Ledger:decision(text)
  local parts = vim.split(vim.trim(text or ''), '%s+%-%-%s+', { trimempty = false })
  local title = vim.trim(parts[1] or '')
  if title == '' then
    return nil, 'empty decision'
  end
  return self:add_decision({ title = title, reason = parts[2], alternatives = parts[3], source = 'you' })
end

