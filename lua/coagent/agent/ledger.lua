--- Turn the reply into overview.md sections (canonical names and order).
---@param text string
---@return table<string,string>? sections, string? err
function M.overview_sections(text)
  text = vim.trim(text or '')
  local inner = text:match('^```%w*\n(.*)\n```$')
  if inner then
    text = inner
  end
  local doc = M.parse(text)
  local out, found = {}, 0
  for _, name in ipairs(M.SECTIONS.overview) do
    local s = M.section(doc, name)
    if s and not M.is_placeholder(s.body) then
      found = found + 1
      out[name] = clean_block(s.body, 16000)
    else
      out[name] = '_(not determined)_'
    end
  end
  if found == 0 then
    return nil, 'the reply has none of the overview sections'
  end
  -- the directory tree is a code block: keep it verbatim (only redacted)
  local tree = M.section(doc, 'Directory tree')
  if tree and not M.is_placeholder(tree.body) then
    out['Directory tree'] = util.clip(util.redact(tree.body), 16000)
  end
  return out
end

---@param kind 'overview'|'update'
---@param system string
---@param user string
---@return string? text, string? err, string? model
function Ledger:_ask(kind, system, user)
  local ctrl = self.ctrl
  if not (ctrl and ctrl.backend) then
    return nil, 'no backend'
  end
  async.main()
  local model = (kind == 'update' and self.config.update_model) or self.config.model or ctrl:model()
  local res, err = ctrl.backend:ask({
    messages = { { role = 'user', content = user } },
    system_prompt = system,
    tools = {},
    model = model,
    temperature = ctrl.config.temperature,
    effort = ctrl:roles().builder_effort,
    role = 'ledger',
    -- independent of the agent's own (cancellable) request
    headless = true,
  })
  async.main()
  pcall(ctrl._record_role, ctrl, 'ledger', model, res)
  if not res or res.cancelled then
    return nil, err or 'cancelled', model
  end
  local text = vim.trim(res.content or '')
  if text == '' then
    return nil, err or 'empty reply', model
  end
  return text, nil, model
end

--- Run jobs (requests + writes) one at a time.
function Ledger:_job(label, fn, cb)
  table.insert(self.jobs, { label = label, fn = fn, cb = cb })
  self:_pump()
end

function Ledger:_pump()
  if self.running or #self.jobs == 0 then
    return
  end
  local job = table.remove(self.jobs, 1)
  self.running = job.label
  async.run(function()
    local ok, a, b = xpcall(job.fn, debug.traceback)
    async.main()
    self.running = nil
    if not ok then
      self:_notice('error', 'Ledger ' .. job.label .. ' failed: ' .. tostring(a))
      a, b = false, tostring(a)
    end
    if job.cb then
      pcall(job.cb, a, b)
    end
    vim.schedule(function()
      self:_pump()
    end)
  end)
end

--- A request or write is queued or running.
function Ledger:busy()
  return self.running ~= nil or #self.jobs > 0
end

function Ledger:_finish_overview(sections, model, how)
  local r = self:update_sections('overview', sections)
  local m = self:_meta()
  m.sources = self:_fingerprint(self:_sources_in(self:read('overview')))
  m.overview = { generated = m.overview and m.overview.generated or os.time(), updated = os.time(), model = model }
  self:_save_meta(m)
  local msg = string.format('Ledger: overview.md %s (%d sections; %d files tracked for staleness).', how, #r.applied, #m.sources)
  if #r.pending > 0 then
    msg = msg .. ' You edited ' .. table.concat(r.pending, ', ') .. ': those updates wait for /ledger review.'
    self:_notice('warn', msg)
  else
    self:_notice('info', msg)
  end
  return r
end

--- `/ledger init`: create the ledger and generate overview.md with ONE
--- request without tools (coagent reads the tree and the core files itself).
---@param cb fun(ok:boolean, err:string?)?
---@return boolean started, string? err
function Ledger:init(cb)
  if not self:enabled() then
    return false, 'the ledger is disabled (ledger.enabled = false)'
  end
  self:ensure()
  self:_job('init', function()
    local paths = M.list_files(self.ws.root)
    local files, considered = self:_read_files(paths, {
      max_bytes = self.config.init_max_bytes or 160 * 1024,
      max_file_bytes = self.config.max_file_bytes or 24 * 1024,
    })
    local parts = {
      'Write overview.md for the project "' .. vim.fs.basename(self.ws.root) .. '".',
      string.format('<directory_tree files="%d">\n%s\n</directory_tree>', #paths, M.tree(paths, self.config.tree_max_entries or 300)),
      string.format('<core_files read="%d" candidates="%d">\n%s\n</core_files>', #files, considered, files_block(files)),
    }
    local exp = self:experiments_summary(5)
    if exp then
      table.insert(parts, '<experiment_log>\n' .. exp .. '\n</experiment_log>')
    end
    self:_notice('info', string.format('Ledger: generating overview.md from %d core files (1 request)...', #files))
    local text, err, model = self:_ask('overview', M.INIT_PROMPT, table.concat(parts, '\n\n'))
    if not text then
      self:_notice('error', 'Ledger init: the request failed: ' .. tostring(err))
      return false, err
    end
    local sections, perr = M.overview_sections(text)
    if not sections then
      self:_notice('error', 'Ledger init: ' .. perr .. '; overview.md unchanged.')
      return false, perr
    end
    self:_finish_overview(sections, model, 'generated')
    return true
  end, cb)
  return true
end

--- `/ledger refresh`: regenerate the overview (ONE request) when files it
--- lists changed; `force` regenerates it anyway.
---@param opts {force:boolean?}?
---@param cb fun(ok:boolean, err:string?)?
---@return boolean started, string? err
function Ledger:refresh(opts, cb)
  opts = opts or {}
  if not self:initialized() then
    return false, 'no overview yet: /ledger init'
  end
  local stale = self:stale()
  if not stale and not opts.force then
    return false, 'the overview is up to date (none of the files it lists changed); /ledger refresh! regenerates it anyway'
  end
  stale = stale or { changed = {}, missing = {} }
  self:_job('refresh', function()
    local paths = M.list_files(self.ws.root)
    local only = vim.deepcopy(stale.changed)
    if opts.force then
      for _, s in ipairs(self:_meta().sources or {}) do
        if not vim.tbl_contains(only, s.path) and not vim.tbl_contains(stale.missing, s.path) then
          table.insert(only, s.path)
        end
      end
    end
    local files = self:_read_files(paths, {
      only = only,
      max_bytes = self.config.init_max_bytes or 160 * 1024,
      max_file_bytes = self.config.max_file_bytes or 24 * 1024,
    })
    local list = {}
    for _, p in ipairs(stale.changed) do
      table.insert(list, '- changed: `' .. p .. '`')
    end
    for _, p in ipairs(stale.missing) do
      table.insert(list, '- deleted or moved: `' .. p .. '`')
    end
    local parts = {
      '<current_overview>\n' .. strip_comments(self:read('overview')) .. '\n</current_overview>',
      '<changed_files>\n' .. (#list > 0 and table.concat(list, '\n') or '(none: full refresh requested)') .. '\n</changed_files>',
      string.format('<directory_tree files="%d">\n%s\n</directory_tree>', #paths, M.tree(paths, self.config.tree_max_entries or 300)),
      '<files>\n' .. files_block(files) .. '\n</files>',
    }
    self:_notice('info', string.format('Ledger: refreshing overview.md (%d changed, %d deleted files; 1 request)...', #stale.changed, #stale.missing))
    local text, err, model = self:_ask('overview', M.REFRESH_PROMPT, table.concat(parts, '\n\n'))
    if not text then
      self:_notice('error', 'Ledger refresh: the request failed: ' .. tostring(err))
      return false, err
    end
    local sections, perr = M.overview_sections(text)
    if not sections then
      self:_notice('error', 'Ledger refresh: ' .. perr .. '; overview.md unchanged.')
      return false, perr
    end
    self:_finish_overview(sections, model, 'refreshed')
    return true
  end, cb)
  return true
end

