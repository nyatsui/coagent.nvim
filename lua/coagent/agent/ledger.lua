local function mtime(st)
  return st.mtime.sec .. '.' .. (st.mtime.nsec or 0)
end

--- Workspace files the overview names in `backticks` (outside code fences).
---@param text string
---@return string[]
function Ledger:_sources_in(text)
  local seen, out, fence = {}, {}, false
  for _, line in ipairs(vim.split(text or '', '\n', { plain = true })) do
    if is_fence(line) then
      fence = not fence
    elseif not fence then
      for tok in line:gmatch('`([^`\n]+)`') do
        local p = tok:gsub(':%d+.*$', ''):gsub('^%./', '')
        if not seen[p] and #p < 300 and not p:match('%s') and not p:match('^/') and not p:match('%.%.') then
          seen[p] = true
          local st = vim.uv.fs_stat(self.ws.root .. '/' .. p)
          if st and st.type == 'file' and #out < 200 then
            table.insert(out, p)
          end
        end
      end
    end
  end
  table.sort(out)
  return out
end

function Ledger:_fingerprint(paths)
  local out = {}
  for _, p in ipairs(paths) do
    local abs = self.ws.root .. '/' .. p
    local st = vim.uv.fs_stat(abs)
    if st then
      table.insert(out, { path = p, sha = sha(util.read_file(abs) or ''), size = st.size, mtime = mtime(st) })
    end
  end
  return out
end

--- Files listed in the overview that changed (content sha) or disappeared
--- since it was generated. nil = up to date (or no overview yet).
---@return {changed:string[], missing:string[]}?
function Ledger:stale()
  if not self:exists() then
    return nil
  end
  local m = self:_meta()
  if type(m.sources) ~= 'table' or #m.sources == 0 then
    return nil
  end
  local changed, missing, touched = {}, {}, false
  for _, s in ipairs(m.sources) do
    local abs = self.ws.root .. '/' .. s.path
    local st = vim.uv.fs_stat(abs)
    if not st then
      table.insert(missing, s.path)
    elseif st.size ~= s.size or mtime(st) ~= s.mtime then
      if sha(util.read_file(abs) or '') ~= s.sha then
        table.insert(changed, s.path)
      else
        s.size, s.mtime, touched = st.size, mtime(st), true -- touched, same content
      end
    end
  end
  if touched then
    self:_save_meta(m)
  end
  if #changed + #missing == 0 then
    return nil
  end
  return { changed = changed, missing = missing }
end

