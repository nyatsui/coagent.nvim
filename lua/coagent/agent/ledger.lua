--- Workspace files, relative, sorted (git's view when available).
---@param root string
---@return string[]
function M.list_files(root)
  local out = {}
  local res = vim.system(vim.list_extend({ 'git', '-C', root, 'ls-files', '-co', '--exclude-standard' }, Workspace.git_pathspec(true)), { text = true }):wait(5000)
  if res and res.code == 0 then
    for line in (res.stdout or ''):gmatch('[^\n]+') do
      table.insert(out, line)
      if #out >= 20000 then
        break
      end
    end
  else
    for name, type in vim.fs.dir(root, {
      depth = 8,
      skip = function(dir)
        return not SKIP_DIRS[vim.fs.basename(dir)]
      end,
    }) do
      if type == 'file' then
        table.insert(out, name)
        if #out >= 20000 then
          break
        end
      end
    end
  end
  local kept = {}
  for _, p in ipairs(out) do
    local skip = false
    for part in p:gmatch('[^/]+') do
      if SKIP_DIRS[part] then
        skip = true
        break
      end
    end
    if not skip then
      table.insert(kept, p)
    end
  end
  table.sort(kept)
  return kept
end

--- Indented tree of `paths` (directories first; long directories collapsed).
---@param paths string[]
---@param max_entries integer
---@return string
function M.tree(paths, max_entries)
  local root = { dirs = {}, files = {}, n = 0 }
  for _, p in ipairs(paths) do
    local node = root
    local parts = vim.split(p, '/', { plain = true })
    for i = 1, #parts - 1 do
      node.n = node.n + 1
      node.dirs[parts[i]] = node.dirs[parts[i]] or { dirs = {}, files = {}, n = 0 }
      node = node.dirs[parts[i]]
    end
    node.n = node.n + 1
    table.insert(node.files, parts[#parts])
  end
  local lines, truncated = {}, false
  local function emit(line)
    if #lines >= max_entries then
      truncated = true
      return false
    end
    table.insert(lines, line)
    return true
  end
  local function walk(node, indent, depth)
    local names = vim.tbl_keys(node.dirs)
    table.sort(names)
    for _, d in ipairs(names) do
      local child = node.dirs[d]
      if depth >= 4 or (DATA_DIRS[d:lower()] and child.n > 10) then
        if not emit(string.format('%s%s/ (%d files)', indent, d, child.n)) then
          return
        end
      else
        if not emit(indent .. d .. '/') then
          return
        end
        walk(child, indent .. '  ', depth + 1)
      end
    end
    table.sort(node.files)
    for i, f in ipairs(node.files) do
      if i > 25 then
        emit(string.format('%s… %d more files', indent, #node.files - 25))
        break
      end
      if not emit(indent .. f) then
        return
      end
    end
  end
  walk(root, '', 0)
  if truncated then
    table.insert(lines, string.format('… (tree truncated: %d files in total)', #paths))
  end
  return table.concat(lines, '\n')
end

