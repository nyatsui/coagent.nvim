---@class Coagent.Ledger
---@field config table ledger config
---@field full table full coagent config
---@field ws table workspace
---@field ctrl Coagent.Controller? requests, notices
---@field experiments Coagent.Experiments?
local Ledger = {}
Ledger.__index = Ledger
M.Ledger = Ledger

-- One instance per ledger directory, shared by every controller of the
-- project, so updates queued by one session never race another's writes.
local instances = {}

---@param config table full coagent config
---@param ws table workspace
---@param opts {experiments:Coagent.Experiments?, ctrl:Coagent.Controller?}?
---@return Coagent.Ledger
function M.new(config, ws, opts)
  opts = opts or {}
  local self = setmetatable({ config = (config and config.ledger) or {}, full = config or {}, ws = ws, jobs = {} }, Ledger)
  local key = self:dir()
  local shared = instances[key]
  if shared then
    shared.config, shared.full, shared.ws = self.config, self.full, ws
    self = shared
  else
    instances[key] = self
  end
  self.experiments = opts.experiments or self.experiments
  self.ctrl = opts.ctrl or self.ctrl
  return self
end

function M._reset()
  instances = {}
end

function Ledger:enabled()
  return self.config.enabled ~= false
end

--- Same project key as the session store / experiment log.
---@return string
function Ledger:dir()
  local root = self.ws.root
  if self.config.dir_in_repo and self.config.dir_in_repo ~= '' then
    local rel = vim.fs.normalize(self.config.dir_in_repo):gsub('^%./', ''):gsub('/+$', '')
    return root .. '/' .. rel
  end
  local base = self.config.dir and vim.fs.normalize(self.config.dir) or (vim.fn.stdpath('state') .. '/coagent/ledger')
  local key = vim.fs.basename(root):gsub('[^%w%-_%.]', '_') .. '-' .. vim.fn.sha256(root):sub(1, 12)
  return base .. '/' .. key
end

---@param name string one of M.FILES
function Ledger:path(name)
  return self:dir() .. '/' .. name .. '.md'
end

--- Has the ledger been created for this project (/ledger, /ledger init)?
function Ledger:exists()
  return vim.uv.fs_stat(self:path('goals')) ~= nil
end

--- Has /ledger init generated the overview?
function Ledger:initialized()
  return self:_meta().overview ~= nil
end

function Ledger:_notice(level, text)
  if self.ctrl then
    self.ctrl:notice(level, text)
  else
    vim.notify('[coagent] ' .. text, level == 'error' and vim.log.levels.ERROR or (level == 'warn' and vim.log.levels.WARN or vim.log.levels.INFO))
  end
end

local function ensure_dir(dir)
  if vim.fn.isdirectory(dir) == 0 then
    vim.fn.mkdir(dir, 'p', DIR_MODE)
  end
  vim.uv.fs_chmod(dir, DIR_MODE)
end

local function write(path, text)
  local ok, err = util.write_file(path, text, FILE_MODE)
  vim.uv.fs_chmod(path, FILE_MODE)
  return ok, err
end

---@return table
function Ledger:_meta()
  local data = util.read_file(self:dir() .. '/.meta.json')
  local m = data and util.json_decode(data)
  if type(m) ~= 'table' then
    m = {}
  end
  m.written = type(m.written) == 'table' and m.written or {}
  m.pending = type(m.pending) == 'table' and m.pending or {}
  m.queued = type(m.queued) == 'table' and m.queued or {}
  m.last_id = type(m.last_id) == 'table' and m.last_id or {}
  return m
end

function Ledger:_save_meta(m)
  ensure_dir(self:dir())
  write(self:dir() .. '/.meta.json', vim.json.encode(m))
end

--- Create the directory and any missing file (from the templates).
---@return boolean created something
function Ledger:ensure()
  local dir = self:dir()
  ensure_dir(dir)
  local created = false
  local m = self:_meta()
  for _, name in ipairs(M.FILES) do
    local path = self:path(name)
    if not vim.uv.fs_stat(path) then
      local text = template(name)
      write(path, text)
      created = true
      -- the template is what coagent wrote: filling it in counts as your edit
      local w = {}
      for _, s in ipairs(M.parse(text).sections) do
        w[s.name] = M.section_hash(s.body)
      end
      m.written[name] = w
    else
      vim.uv.fs_chmod(path, FILE_MODE)
    end
  end
  if created or not vim.uv.fs_stat(dir .. '/.meta.json') then
    self:_save_meta(m)
  end
  return created
end

---@param name string
---@return string
function Ledger:read(name)
  return util.read_file(self:path(name)) or ''
end

--- Loaded buffer of a ledger file with unsaved changes?
function Ledger:_dirty(name)
  local buf = util.find_buf(self:path(name))
  return buf ~= nil and vim.bo[buf].modified
end

--- Write a ledger file; reload an open (unmodified) buffer of it.
function Ledger:_write(name, text)
  ensure_dir(self:dir())
  local path = self:path(name)
  local ok, err = write(path, text)
  local buf = util.find_buf(path)
  if ok and buf and not vim.bo[buf].modified then
    pcall(vim.api.nvim_buf_call, buf, function()
      vim.cmd('silent! edit')
    end)
  end
  return ok, err
end

---@class Coagent.LedgerPending
---@field file string
---@field section string
---@field proposed string
---@field time integer
---@field reason string

--- Replace sections of `name` with `proposed` (section name -> body), never
--- overwriting a section you edited (its text differs from what coagent last
--- wrote) or a file with unsaved changes in a buffer: those updates are kept
--- in meta.pending for /ledger review.
---@param name string
---@param proposed table<string,string>
---@param order string[]? section order for new sections (default M.SECTIONS[name])
---@return {applied:string[], pending:string[]}
function Ledger:update_sections(name, proposed, order)
  self:ensure()
  local m = self:_meta()
  local result = { applied = {}, pending = {} }
  local dirty = self:_dirty(name)
  local doc = M.parse(self:read(name))
  if doc.preamble == '' then
    doc.preamble = M.parse(template(name)).preamble
  end
  local written = m.written[name] or {}
  m.written[name] = written
  local function add_pending(sec, body, reason)
    for i = #m.pending, 1, -1 do
      local p = m.pending[i]
      if p.file == name and p.section:lower() == sec:lower() then
        table.remove(m.pending, i)
      end
    end
    table.insert(m.pending, { file = name, section = sec, proposed = body, time = os.time(), reason = reason })
    table.insert(result.pending, sec)
  end
  local names = {}
  for _, s in ipairs(order or M.SECTIONS[name] or {}) do
    if proposed[s] ~= nil then
      table.insert(names, s)
    end
  end
  for s in pairs(proposed) do
    if not vim.tbl_contains(names, s) then
      table.insert(names, s)
    end
  end
  local changed = false
  for _, sec in ipairs(names) do
    local new = body_of(proposed[sec])
    local cur = M.section(doc, sec)
    if dirty then
      add_pending(sec, new, 'unsaved buffer')
    elseif not cur then
      table.insert(doc.sections, { name = sec, body = new })
      written[sec] = M.section_hash(new)
      table.insert(result.applied, sec)
      changed = true
    else
      local cur_hash = M.section_hash(cur.body)
      local base = written[cur.name]
      if cur_hash == M.section_hash(new) then
        written[cur.name] = cur_hash -- same text: nothing to protect
      elseif base == cur_hash or (base == nil and M.is_placeholder(cur.body)) then
        cur.body = new
        written[cur.name] = M.section_hash(new)
        table.insert(result.applied, cur.name)
        changed = true
      else
        add_pending(cur.name, new, 'edited by you')
      end
    end
  end
  if changed then
    self:_write(name, M.render(doc))
  end
  self:_save_meta(m)
  return result
end

--- Pending updates of sections you edited.
---@return Coagent.LedgerPending[]
function Ledger:pending()
  return self:_meta().pending
end

--- Unified diff of a pending update (your current text -> the proposal).
---@param p Coagent.LedgerPending
---@return string
function Ledger:pending_diff(p)
  local cur = M.section(M.parse(self:read(p.file)), p.section)
  local old = (cur and body_of(cur.body) or '') .. '\n'
  local new = body_of(p.proposed) .. '\n'
  return require('coagent.core.diff').unified(old, new, p.file .. '.md#' .. p.section)
end

--- Apply (`'apply'`) or drop (`'keep'`: your text stays and becomes the new
--- baseline) a pending update.
---@param index integer
---@param action 'apply'|'keep'
---@return boolean ok, string? err
function Ledger:resolve(index, action)
  local m = self:_meta()
  local p = m.pending[index]
  if not p then
    return false, 'no pending update ' .. tostring(index)
  end
  if self:_dirty(p.file) then
    return false, p.file .. '.md has unsaved changes in a buffer; save it first'
  end
  table.remove(m.pending, index)
  local doc = M.parse(self:read(p.file))
  local cur = M.section(doc, p.section)
  m.written[p.file] = m.written[p.file] or {}
  if action == 'apply' then
    if cur then
      cur.body = p.proposed
    else
      table.insert(doc.sections, { name = p.section, body = p.proposed })
    end
    m.written[p.file][p.section] = M.section_hash(p.proposed)
    self:_write(p.file, M.render(doc))
  else
    m.written[p.file][cur and cur.name or p.section] = cur and M.section_hash(cur.body) or nil
  end
  self:_save_meta(m)
  return true
end

