---@return string[]
function Ledger:info_lines()
  local lines = { 'Ledger: ' .. vim.fn.fnamemodify(self:dir(), ':~') .. (self.config.dir_in_repo and ' (in the repository)' or '') }
  if not self:exists() then
    table.insert(lines, 'Not created yet: /ledger init generates the overview (1 request); /ledger opens empty files.')
    return lines
  end
  local m = self:_meta()
  table.insert(lines, m.overview and ('overview.md generated ' .. os.date('%Y-%m-%d %H:%M', m.overview.updated or m.overview.generated) .. ' (' .. #(m.sources or {}) .. ' files tracked)') or 'overview.md not generated yet (/ledger init)')
  local st = self:stale()
  if st then
    table.insert(lines, string.format('Overview is STALE: %d changed, %d deleted (%s); /ledger refresh', #st.changed, #st.missing, table.concat(vim.list_slice(vim.list_extend(vim.deepcopy(st.changed), st.missing), 1, 5), ', ')))
  end
  table.insert(lines, string.format('%d decisions, %d subtasks; auto_update = %s', #M.entries(self:read('decisions'), 'D'), #M.entries(self:read('subtasks'), 'S'), tostring(self.config.auto_update ~= false)))
  if #m.pending > 0 then
    table.insert(lines, #m.pending .. ' pending update(s) of sections you edited: /ledger review')
  end
  if #m.queued > 0 then
    table.insert(lines, #m.queued .. ' entr' .. (#m.queued == 1 and 'y waits' or 'ies wait') .. ' for an unsaved ledger buffer')
  end
  return lines
end

